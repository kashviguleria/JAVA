

public class nestedloops {
    public static void main(String[] args) {
        //if loop runs like i=5 j=5 so total will be 5*5=25
        for(int i=1;i<=5;i++){
            for(int j=1;j<=5;j++){
                System.out.print(i+" "+j+"  ");
            }
            System.out.println();
        }

    }
    }

